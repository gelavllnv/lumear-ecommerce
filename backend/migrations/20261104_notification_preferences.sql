CREATE TABLE IF NOT EXISTS mobile_notification_preferences (
 user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 order_updates BOOLEAN NOT NULL DEFAULT TRUE,
 promotions BOOLEAN NOT NULL DEFAULT TRUE,
 general_updates BOOLEAN NOT NULL DEFAULT TRUE,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT mobile_notification_preferences_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
